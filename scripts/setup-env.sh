#!/usr/bin/env bash
set -e

FORCE=false
if [ "$1" = "--force" ]; then
  FORCE=true
fi

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_EXAMPLE="$ROOT_DIR/.env.example"
ENV_FILE="$ROOT_DIR/.env"
WEB_ENV_LOCAL="$ROOT_DIR/apps/web/.env.local"

if [ -f "$ENV_FILE" ] && [ "$FORCE" = false ]; then
  echo "⚠️  .env already exists! Use --force to overwrite: bash scripts/setup-env.sh --force"
  exit 0
fi

echo "🚀 Generating .env from .env.example..."
cp "$ENV_EXAMPLE" "$ENV_FILE"

# Generate random secrets
generate_secret() {
  node -e "console.log(require('crypto').randomBytes(32).toString('hex'))"
}

ADMIN_PASS=$(generate_secret)
MONGO_PASS=$(generate_secret)
REDIS_PASS=$(generate_secret)
JWT_ACCESS=$(generate_secret)
JWT_REFRESH=$(generate_secret)
COOKIE_SECRET=$(generate_secret)
PAYMENT_SECRET=$(generate_secret)
MINIO_PASS=$(generate_secret)
HASH_SALT=$(generate_secret)
GRAFANA_PASS=$(generate_secret)

# Generate VAPID keys if possible, or fallback to crypto base64url keys
VAPID_KEYS=$(node -e "
  const crypto = require('crypto');
  const pub = crypto.randomBytes(33).toString('base64url');
  const priv = crypto.randomBytes(32).toString('base64url');
  console.log(pub + ' ' + priv);
")
VAPID_PUB=$(echo "$VAPID_KEYS" | cut -d ' ' -f 1)
VAPID_PRIV=$(echo "$VAPID_KEYS" | cut -d ' ' -f 2)

# Replace placeholders
sed -i.bak \
  -e "s|CHANGE_ME_SEED_ADMIN_PASSWORD|$ADMIN_PASS|g" \
  -e "s|CHANGE_ME_MONGO_ROOT_PASSWORD|$MONGO_PASS|g" \
  -e "s|CHANGE_ME_REDIS_PASSWORD|$REDIS_PASS|g" \
  -e "s|CHANGE_ME_JWT_ACCESS_SECRET|$JWT_ACCESS|g" \
  -e "s|CHANGE_ME_JWT_REFRESH_SECRET|$JWT_REFRESH|g" \
  -e "s|CHANGE_ME_COOKIE_SECRET|$COOKIE_SECRET|g" \
  -e "s|CHANGE_ME_PAYMENT_SIM_WEBHOOK_SECRET|$PAYMENT_SECRET|g" \
  -e "s|CHANGE_ME_MINIO_ROOT_PASSWORD|$MINIO_PASS|g" \
  -e "s|CHANGE_ME_HASH_SALT|$HASH_SALT|g" \
  -e "s|CHANGE_ME_GRAFANA_ADMIN_PASSWORD|$GRAFANA_PASS|g" \
  -e "s|GENERATED_BY_SETUP_SCRIPT|$VAPID_PUB|g" \
  "$ENV_FILE"

sed -i.bak -e "s|VAPID_PRIVATE_KEY=$VAPID_PUB|VAPID_PRIVATE_KEY=$VAPID_PRIV|g" "$ENV_FILE"
rm -f "$ENV_FILE.bak"

# Create infra/mongo-sharding directory and keyfile
mkdir -p "$ROOT_DIR/infra/mongo-sharding"
if command -v openssl >/dev/null 2>&1; then
  openssl rand -base64 756 > "$ROOT_DIR/infra/mongo-sharding/keyfile" 2>/dev/null || true
  chmod 400 "$ROOT_DIR/infra/mongo-sharding/keyfile" 2>/dev/null || true
fi

# Create apps/web/.env.local with browser-safe variables
mkdir -p "$ROOT_DIR/apps/web"
cat <<EOF > "$WEB_ENV_LOCAL"
# Auto-generated by scripts/setup-env.sh — do not commit
NEXT_PUBLIC_APP_NAME=Hukum
NEXT_PUBLIC_API_BASE_URL=http://localhost:4000
NEXT_PUBLIC_SHORT_BASE_URL=http://localhost:8080
NEXT_PUBLIC_VAPID_PUBLIC_KEY=$VAPID_PUB
NEXT_PUBLIC_AC_DEBOUNCE_MS=100
NEXT_PUBLIC_PAYMENT_SIM_BADGE=true
EOF

echo "✅ Environment generated successfully!"
echo "   - Root: $ENV_FILE"
echo "   - Web:  $WEB_ENV_LOCAL"
echo "   - Keyfile: $ROOT_DIR/infra/mongo-sharding/keyfile"
